/// Looks up a template by id; `null` = free mode. Unknown ids fall back to
/// free mode so a stale persisted selection never breaks generation.
SummaryTemplate? findSummaryTemplate(String? id) {
  if (id == null || id == 'free' || id.isEmpty) return null;
  for (final t in summaryTemplates) {
    if (t.id == id) return t;
  }
  return null;
}
