/// Summary templates + the G_SPEC output contract for the AI Parse page —
/// ported verbatim from the voice_transcription reference project
/// (`src/lib/ai/templates.ts`).
///
/// The 25 templates are pure prompt data: scenario-grouped, each carrying a
/// full prompt with `{{占位符}}` input declarations and the shared G_SPEC
/// contract. The free-form mode (`selectedTemplateId == 'free'`) uses the
/// generic summarizer prompt + G_SPEC instead (see summarize_pipeline.dart).
library;

/// One summary template.
class SummaryTemplate {
  final String id;
  final String scenario;
  final String name;
  final String type;
  final String desc;

  /// Expected input description (display only).
  final String input;

  /// Output module list (display only).
  final List<String> modules;

  /// Full prompt (contains its own {{placeholders}} and G-SPEC contract).
  final String prompt;

  const SummaryTemplate({
    required this.id,
    required this.scenario,
    required this.name,
    required this.type,
    required this.desc,
    required this.input,
    required this.modules,
    required this.prompt,
  });
}

/// Scenario group.
class SummaryScenario {
  final String id;
  final String label;

  const SummaryScenario({required this.id, required this.label});
}

